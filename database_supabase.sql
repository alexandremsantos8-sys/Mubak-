-- Mubak - estrutura de dados para PostgreSQL/Supabase
-- Gerado a partir das entidades, services, repositories, templates e schema.sql.
-- Este script nao insere dados existentes. Os arquivos atuais de uploads devem
-- ser enviados separadamente para o Supabase Storage.

BEGIN;

CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    documento VARCHAR(14) NOT NULL,
    data_nascimento DATE NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(20) NOT NULL DEFAULT 'CLIENTE',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT usuarios_documento_key UNIQUE (documento),
    CONSTRAINT usuarios_email_key UNIQUE (email),
    CONSTRAINT usuarios_perfil_check CHECK (perfil IN ('CLIENTE', 'ROOT')),
    CONSTRAINT usuarios_documento_tamanho_check CHECK (length(documento) IN (11, 14))
);

CREATE OR REPLACE FUNCTION public.normalizar_usuario()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.email := lower(trim(NEW.email));
    NEW.documento := regexp_replace(NEW.documento, '[^0-9]', '', 'g');
    NEW.atualizado_em := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS usuarios_normalizacao ON public.usuarios;
CREATE TRIGGER usuarios_normalizacao
BEFORE INSERT OR UPDATE ON public.usuarios
FOR EACH ROW
EXECUTE FUNCTION public.normalizar_usuario();

CREATE TABLE IF NOT EXISTS public.produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(2000) NOT NULL,
    preco NUMERIC(12, 2) NOT NULL,
    estoque INTEGER NOT NULL DEFAULT 0,
    imagem_url VARCHAR(500) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    vendedor VARCHAR(120) NOT NULL,
    CONSTRAINT produtos_preco_check CHECK (preco > 0),
    CONSTRAINT produtos_estoque_check CHECK (estoque >= 0)
);

-- A aplicacao atual grava a imagem diretamente em produtos.imagem_url.
-- Esta tabela permite migrar os arquivos de uploads para o Supabase Storage
-- sem perder o nome original, MIME type ou o caminho no bucket.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.imagens (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    produto_id BIGINT NOT NULL REFERENCES public.produtos(id) ON DELETE CASCADE,
    url VARCHAR(1000) NOT NULL,
    storage_bucket VARCHAR(100) NOT NULL DEFAULT 'produtos',
    storage_path VARCHAR(500),
    nome_original VARCHAR(255),
    tipo_mime VARCHAR(100) NOT NULL,
    tamanho_bytes BIGINT,
    principal BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT imagens_tamanho_check CHECK (tamanho_bytes IS NULL OR tamanho_bytes >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS imagens_produto_principal_key
ON public.imagens (produto_id)
WHERE principal;

CREATE INDEX IF NOT EXISTS produtos_nome_idx
ON public.produtos (lower(nome));

CREATE INDEX IF NOT EXISTS produtos_categoria_idx
ON public.produtos (lower(categoria));

CREATE INDEX IF NOT EXISTS imagens_produto_id_idx
ON public.imagens (produto_id);

COMMENT ON TABLE public.usuarios IS
'Contas de clientes e administradores ROOT usadas no login e na sessao.';
COMMENT ON COLUMN public.usuarios.senha_hash IS
'Hash SHA-256 hexadecimal gerado pela aplicacao atual; nao armazena a senha em texto.';
COMMENT ON TABLE public.produtos IS
'Catalogo de produtos persistido pela entidade Java produto.';
COMMENT ON COLUMN public.produtos.vendedor IS
'Texto livre conforme o modelo atual; nao e uma chave estrangeira para usuarios.';
COMMENT ON COLUMN public.produtos.imagem_url IS
'URL ou caminho publico da imagem usado diretamente pelas telas atuais.';
COMMENT ON TABLE public.imagens IS
'Metadados opcionais para arquivos enviados ao Supabase Storage.';

COMMIT;
